#!/usr/bin/env python3
"""Vendor the simulator's feedback policies into ``simpolicies/`` for the GPU box.

``replica_pool.py`` runs ``reactive`` and ``velocity`` on the box with the same code the simulator
uses, but the box has no ``pilot`` package.  This script copies four files
of ``src/pilot/sim`` next to the pool script, byte for byte except for the two relative
import lines that pointed at the package root, generates the package ``__init__.py`` (the
``register_policy`` / ``POLICY_FACTORY`` pair of ``pilot.sim`` with the same semantics) and a
``MANIFEST.json`` with the sha256 of every source and every generated file.  The manifest travels
into ``pool_meta.json`` so that the laptop-side comparison can prove the policy code that ran on
the box is the policy code the simulator ran.

Idempotent: files are rewritten only when their content changed, and the timestamp in the
manifest moves only when a file did.

    python vendor_policies.py            # regenerate scripts/q2/simpolicies/
    python vendor_policies.py --check    # exit 1 when the vendored copy is stale
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import sys
import time
from pathlib import Path

logger = logging.getLogger("q2.vendor_policies")

HERE = Path(__file__).resolve().parent
PILOT_DIR = HERE.parents[1]
SIM_DIR = PILOT_DIR / "src" / "pilot" / "sim"
PACKAGE_DIR = HERE / "simpolicies"
MANIFEST_NAME = "MANIFEST.json"
SCHEMA = "q2.simpolicies.manifest.v1"

SOURCES: dict[str, Path] = {
    "config.py": SIM_DIR / "config.py",
    "base.py": SIM_DIR / "policies" / "base.py",
    "reactive.py": SIM_DIR / "policies" / "reactive.py",
    "velocity.py": SIM_DIR / "policies" / "velocity.py",
}
# the only edits allowed: the two relative imports that reached past ``policies/`` to the package
REWRITES: tuple[tuple[str, str], ...] = (
    ("from .. import register_policy", "from . import register_policy"),
    ("from ..config import", "from .config import"),
)

INIT_SOURCE = '''"""Vendored copy of the simulator's feedback policies for the GPU box (generated file).

Generated by ``scripts/q2/vendor_policies.py`` from ``src/pilot/sim``; do not edit by
hand.  ``config.py``, ``base.py``, ``reactive.py`` and ``velocity.py`` are byte-identical to their
sources except for the import lines listed in ``MANIFEST.json``.  ``register_policy`` and
``POLICY_FACTORY`` are the registry of ``pilot.sim`` with the same semantics: importing this
package registers ``reactive`` and ``velocity``.
"""

import logging
from typing import Callable, Dict, Type

from .config import CostConfig, PolicyConfig, ServiceConfig

logger = logging.getLogger(__name__)

POLICY_FACTORY: Dict[str, Type] = {}


def register_policy(name: str) -> Callable[[Type], Type]:
    """Register a ``Policy`` subclass under ``name``."""

    def decorator(cls: Type) -> Type:
        POLICY_FACTORY[name] = cls
        logger.debug("registered policy %s", name)
        return cls

    return decorator


def PolicyFactory(name: str) -> Type:
    """Return the policy class registered under ``name``."""
    try:
        return POLICY_FACTORY[name]
    except KeyError as exc:
        raise KeyError(f"unknown policy '{name}'; known: {sorted(POLICY_FACTORY)}") from exc


from .base import (  # noqa: E402  (after the registry exists; the modules register on import)
    Policy,
    PolicyContext,
    SimState,
    as_int_plan,
    as_int_replicas,
)
from .reactive import ReactivePolicy  # noqa: E402
from .velocity import TokenVelocityPolicy  # noqa: E402

__all__ = [
    "POLICY_FACTORY",
    "CostConfig",
    "Policy",
    "PolicyConfig",
    "PolicyContext",
    "PolicyFactory",
    "ReactivePolicy",
    "ServiceConfig",
    "SimState",
    "TokenVelocityPolicy",
    "as_int_plan",
    "as_int_replicas",
    "register_policy",
]
'''


def sha256_bytes(blob: bytes) -> str:
    return hashlib.sha256(blob).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def rewrite_imports(text: str) -> tuple[str, list[str]]:
    """Apply ``REWRITES`` and report which of them touched the file."""
    applied: list[str] = []
    for old, new in REWRITES:
        if old in text:
            text = text.replace(old, new)
            applied.append(f"{old} -> {new}")
    return text, applied


def render_package() -> dict[str, tuple[bytes, dict[str, object]]]:
    """``{file name: (bytes, manifest entry)}`` for every generated file except the manifest."""
    out: dict[str, tuple[bytes, dict[str, object]]] = {}
    for name, src in SOURCES.items():
        text, applied = rewrite_imports(src.read_text(encoding="utf-8"))
        blob = text.encode("utf-8")
        out[name] = (blob, {
            "sha256": sha256_bytes(blob),
            "source": str(src.relative_to(PILOT_DIR)),
            "source_sha256": sha256_file(src),
            "rewrites": applied,
        })
    init_blob = INIT_SOURCE.encode("utf-8")
    out["__init__.py"] = (init_blob, {"sha256": sha256_bytes(init_blob), "source": None,
                                      "source_sha256": None, "rewrites": []})
    return out


def build_manifest(rendered: dict[str, tuple[bytes, dict[str, object]]],
                   generated_at: str) -> dict[str, object]:
    return {
        "schema": SCHEMA,
        "generator": "scripts/q2/vendor_policies.py",
        "generated_at": generated_at,
        "sim_dir": str(SIM_DIR.relative_to(PILOT_DIR)),
        "sources": {name: {"path": str(src.relative_to(PILOT_DIR)),
                           "sha256": sha256_file(src)} for name, src in SOURCES.items()},
        "generated": {name: entry for name, (_blob, entry) in rendered.items()},
        "rewrites": [f"{old} -> {new}" for old, new in REWRITES],
    }


def _manifest_core(manifest: dict[str, object]) -> dict[str, object]:
    return {k: v for k, v in manifest.items() if k != "generated_at"}


def load_manifest(package_dir: Path = PACKAGE_DIR) -> dict[str, object] | None:
    path = package_dir / MANIFEST_NAME
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        logger.warning("unreadable %s: %s", path, exc)
        return None


def stale_files(package_dir: Path = PACKAGE_DIR) -> list[str]:
    """Names of vendored files that differ from what the current sources would produce."""
    rendered = render_package()
    stale = [name for name, (blob, _entry) in rendered.items()
             if not (package_dir / name).exists() or (package_dir / name).read_bytes() != blob]
    existing = load_manifest(package_dir)
    fresh = build_manifest(rendered, "")
    if existing is None or _manifest_core(existing) != _manifest_core(fresh):
        stale.append(MANIFEST_NAME)
    return stale


def vendor(package_dir: Path = PACKAGE_DIR) -> list[str]:
    """Write the package; return the names of the files that changed."""
    package_dir.mkdir(parents=True, exist_ok=True)
    rendered = render_package()
    changed: list[str] = []
    for name, (blob, _entry) in rendered.items():
        target = package_dir / name
        if target.exists() and target.read_bytes() == blob:
            continue
        target.write_bytes(blob)
        changed.append(name)
    existing = load_manifest(package_dir)
    fresh = build_manifest(rendered, time.strftime("%Y-%m-%dT%H:%M:%S%z"))
    if existing is None or _manifest_core(existing) != _manifest_core(fresh) or changed:
        (package_dir / MANIFEST_NAME).write_text(
            json.dumps(fresh, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        changed.append(MANIFEST_NAME)
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report staleness, write nothing")
    parser.add_argument("--log-level", default="INFO")
    args = parser.parse_args(argv)
    logging.basicConfig(level=args.log_level.upper(), format="%(levelname)s %(message)s")
    missing = [str(p) for p in SOURCES.values() if not p.exists()]
    if missing:
        logger.error("source files missing: %s", ", ".join(missing))
        return 2
    if args.check:
        stale = stale_files()
        if stale:
            logger.error("simpolicies is stale: %s", ", ".join(stale))
            return 1
        logger.info("simpolicies is up to date with %s", SIM_DIR)
        return 0
    changed = vendor()
    logger.info("%s: %s", PACKAGE_DIR, ("wrote " + ", ".join(changed)) if changed else "unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
